device = 0 if torch.cuda.is_available() else -1
pipe = pipeline("text2text-generation", model=OUTPUT_DIR, tokenizer=OUTPUT_DIR, device=device)

def answer_question(question_text, max_length=64):
    prompt = question_text if question_text.lower().startswith("question:") else "question: " + question_text
    out = pipe(prompt, max_length=max_length, do_sample=False, num_return_sequences=1)
    return out[0]["generated_text"]

