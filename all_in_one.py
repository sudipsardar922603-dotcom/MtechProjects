# 2) Zero-shot classification (no training)
# =========================================
from transformers import pipeline

zero_shot = pipeline("zero-shot-classification", model="facebook/bart-large-mnli")

text = "The school boy met with a serious accident while crossing the road."
labels = ["positive", "negative", "neutral"]

print("Zero-shot:", zero_shot(text, candidate_labels=labels))

# =========================================
# 3) One-shot via prompt (no training)
# =========================================
from transformers import pipeline

generator = pipeline("text-generation", model="gpt2")

prompt = """Classify sentiment:
Text: I love this movie! -> Positive
Text: The spacyr code was really difficult to debug from scratch ->"""

out = generator(prompt, max_length=60, do_sample=False)
print("One-shot (prompt continuation):\n", out[0]["generated_text"])

